/**
 * Embeds rule markdown docs (src/entities/rules/config/**\/*.md) into a TS module,
 * so MCP can serve them in every runtime (Next route, stdio, vitest) without fs access.
 *
 * Usage: node scripts/generate-rule-docs.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const CONFIG_DIR = path.join(ROOT, "src/entities/rules/config");
export const OUTPUT_FILE = path.join(CONFIG_DIR, "rule-docs.generated.ts");

const collectMarkdown = (dir) =>
	fs
		.readdirSync(dir, { withFileTypes: true })
		.flatMap((entry) => {
			const full = path.join(dir, entry.name);
			if (entry.isDirectory()) return collectMarkdown(full);
			return entry.name.endsWith(".md") ? [full] : [];
		})
		.sort();

const extractTitle = (content, fallback) => {
	const match = /^#\s+(.+)$/m.exec(content);
	return match ? match[1].trim() : fallback;
};

export const collectRuleDocs = () => {
	const docs = {};

	for (const file of collectMarkdown(CONFIG_DIR)) {
		const id = path.basename(file, ".md");
		const relative = path.relative(CONFIG_DIR, file).split(path.sep).join("/");

		if (docs[id]) {
			throw new Error(
				`Duplicate rule doc id "${id}": ${docs[id].path} and ${relative}`
			);
		}

		const content = fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");
		docs[id] = { path: relative, title: extractTitle(content, id), content };
	}

	return docs;
};

export const buildRuleDocsSource = (docs = collectRuleDocs()) =>
	[
		"// AUTO-GENERATED by scripts/generate-rule-docs.mjs — do not edit.",
		"// Run `npm run rules:docs` after changing any rules *.md file.",
		"",
		`export const RULE_DOCS = ${JSON.stringify(docs, null, "\t")} as const;`,
		"",
		"export type TRuleDocId = keyof typeof RULE_DOCS;",
		""
	].join("\n");

const isMain =
	process.argv[1] &&
	path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

/** Same formatting as `npm run format`, so regeneration never leaves a diff. */
const formatSource = async (source) => {
	const prettier = await import("prettier");
	const options = (await prettier.resolveConfig(OUTPUT_FILE)) ?? {};
	return prettier.format(source, { ...options, filepath: OUTPUT_FILE });
};

if (isMain) {
	const docs = collectRuleDocs();
	const source = await formatSource(buildRuleDocsSource(docs));
	if (
		!fs.existsSync(OUTPUT_FILE) ||
		fs.readFileSync(OUTPUT_FILE, "utf8") !== source
	) {
		fs.writeFileSync(OUTPUT_FILE, source, "utf8");
	}
	console.log(
		`[rules:docs] ${Object.keys(docs).length} docs → ${path.relative(ROOT, OUTPUT_FILE)}`
	);
}
